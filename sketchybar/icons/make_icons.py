def bars(color, off=False):
    rows = [["."] * 16 for _ in range(16)]
    for i, h in enumerate([3, 6, 9, 12]):
        x0 = 1 + i * 4
        for y in range(14 - h, 14):
            for x in range(x0, x0 + 3):
                rows[y][x] = "k" if x in (x0, x0 + 2) or y == 14 - h or y == 13 else color
    if off:
        for i in range(10):
            rows[3 + i][3 + i] = "r"
            rows[3 + i][12 - i] = "r"
    return ["".join(r) for r in rows]

