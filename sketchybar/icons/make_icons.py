# Pixel icons for the bar: 16x16 grids written as 2x PNGs for Retina.
# Pure stdlib, no PIL. Edit a grid, then: python3 make_icons.py
import os, struct, zlib

PAL = {
    ".": None,
    "k": (0, 0, 0), "w": (255, 255, 255), "g": (192, 192, 192), "d": (128, 128, 128),
    "y": (255, 255, 0), "o": (128, 128, 0), "r": (255, 0, 0), "R": (128, 0, 0),
    "G": (0, 128, 0), "L": (0, 255, 0), "b": (0, 0, 128), "B": (0, 0, 255), "c": (0, 255, 255),
}

def png(path, rows, scale=2):
    h, w = len(rows), len(rows[0])
    raw = b""
    for row in rows:
        line = b""
        for ch in row:
            c = PAL[ch]
            px = b"\0\0\0\0" if c is None else bytes(c) + b"\xff"
            line += px * scale
        raw += (b"\0" + line) * scale
    def chunk(t, d):
        return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w * scale, h * scale, 8, 6, 0, 0, 0))
    data += chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(data)

def grid(s):
    rows = [r for r in s.strip("\n").split("\n")]
    assert all(len(r) == 16 for r in rows) and len(rows) == 16, s
    return rows

