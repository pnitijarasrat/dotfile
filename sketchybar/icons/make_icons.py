def battery(level, fill, bolt=False):
    rows = [["."] * 16 for _ in range(16)]
    for x in range(1, 14):
        rows[4][x] = rows[11][x] = "k"
    for y in range(4, 12):
        rows[y][1] = rows[y][13] = "k"
    for y in range(6, 10):
        rows[y][14] = "k"
    for y in range(5, 11):
        for x in range(2, 13):
            rows[y][x] = "w"
    for y in range(6, 10):
        for x in range(3, 3 + level):
            rows[y][x] = fill
    if bolt:
        for x, y in [(7, 6), (6, 7), (7, 7), (8, 7), (9, 7), (7, 8), (8, 8), (7, 9)]:
            rows[y][x] = "y"
    return ["".join(r) for r in rows]

